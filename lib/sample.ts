export function buildSampleBook(today = new Date()): StockBook {
  const lines: StockLine[] = SEEDS.map((seed, index) => ({
    id: `sample-${index + 1}-${seed.code}-${seed.batch}`,
    code: seed.code,
    altCode: seed.altCode,
    name: seed.name,
    expiry: seed.days == null ? null : addDaysIso(today, seed.days),
    expiryRaw: "",
    quantity: seed.quantity,
    unit: seed.unit,
    location: seed.location,
    batch: seed.batch,
    category: seed.category,
  }));

  return {
    fileName: "Sample makeline sheet",
    importedAt: new Date().toISOString(),
    source: "sample",
    lines,
  };
}
